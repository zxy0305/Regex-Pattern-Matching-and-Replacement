from typing import Any, Optional

from django.conf import settings


class FileProcessingError(ValueError):
    pass


@dataclass
class RegexSuggestion:
    pattern: str
    explanation: str
    source: str


def parse_uploaded_file(uploaded_file) -> dict[str, Any]:
    '''
    Parse an uploaded CSV or XLSX file and return structured data.

    Args: uploaded_file: file object from the request

    Returns: A dictionary containing parsed file

    Raises: FileProcessingError
    '''

    if uploaded_file.size > settings.MAX_UPLOAD_BYTES:
        raise FileProcessingError("File is too large.")

    name = uploaded_file.name.lower()
    data = uploaded_file.read()

    if name.endswith(".csv"):
        return _parse_csv(data)
    if name.endswith(".xlsx"):
        return _parse_xlsx(data)
    if name.endswith(".xls"):
        raise FileProcessingError("Legacy .xls files are not supported. Please save as .xlsx or CSV.")

    raise FileProcessingError("Unsupported file type. Upload a CSV or XLSX file.")


def _parse_csv(data: bytes) -> dict[str, Any]:
    text = data.decode("utf-8-sig")
    sample = text[:4096]
    try:
        dialect = csv.Sniffer().sniff(sample)
    except csv.Error:
        dialect = csv.excel

    reader = csv.DictReader(io.StringIO(text), dialect=dialect)
    if not reader.fieldnames:
        raise FileProcessingError("CSV file must include a header row.")

    rows = [{key: value for key, value in row.items()} for row in reader]
    return {"columns": reader.fieldnames, "rows": rows, "rowCount": len(rows)}


def _parse_xlsx(data: bytes) -> dict[str, Any]:
    try:
        from openpyxl import load_workbook
    except ImportError as exc:
        raise FileProcessingError("XLSX support requires openpyxl. Install backend requirements first.") from exc

    workbook = load_workbook(io.BytesIO(data), read_only=True, data_only=True)
    sheet = workbook.active
    values = list(sheet.iter_rows(values_only=True))
    if not values:
        raise FileProcessingError("Spreadsheet is empty.")

    columns = [str(cell).strip() if cell is not None else f"Column {index + 1}" for index, cell in enumerate(values[0])]
    rows = []
    for raw in values[1:]:
        row = {}
        for index, column in enumerate(columns):
            value = raw[index] if index < len(raw) else ""
            row[column] = "" if value is None else str(value)
        rows.append(row)

    return {"columns": columns, "rows": rows, "rowCount": len(rows)}


